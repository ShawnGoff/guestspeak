-- "bitch" was refused and "bitchass" was not.
--
-- Both were working as configured. The filter has two modes: 'word' matches a
-- whole word only, 'substring' matches anywhere after leet-speak and separators
-- are flattened. Substring is the strong one, and it is reserved for terms with
-- no innocent use, because matching anywhere is what refuses Scunthorpe.
--
-- These eight were in 'word' mode and did not need to be. Every one of them was
-- checked against the 235,974-word system dictionary, and no English word
-- contains any of them as a substring — so nothing legitimate is caught by
-- promoting them, and "bitchass", "fuckass" and "assholery" stop working.
--
-- fucker and motherfucker are redundant once fuck is a substring. They are
-- promoted anyway so that reverting one row cannot silently reopen the others.
UPDATE banned_words
   SET match_mode = 'substring'
 WHERE word IN (
   'arsehole', 'asshole', 'bitch', 'bullshit',
   'douchebag', 'fuck', 'fucker', 'motherfucker'
 );

